#!/usr/bin/env python3
"""Convert an 8x16 PSF2 console font to a freestanding C++ header."""

from __future__ import annotations

import gzip
import pathlib
import struct
import sys


PSF2_MAGIC = 0x864AB572


def read_bytes(path: pathlib.Path) -> bytes:
    if path.suffix == ".gz":
        with gzip.open(path, "rb") as f:
            return f.read()
    return path.read_bytes()


def main() -> int:
    if len(sys.argv) != 3:
        print("usage: psf2_to_header.py INPUT.psfu[.gz] OUTPUT.h", file=sys.stderr)
        return 2

    src = pathlib.Path(sys.argv[1])
    dst = pathlib.Path(sys.argv[2])
    data = read_bytes(src)
    if len(data) < 32:
        raise SystemExit("font is too small for a PSF2 header")

    magic, version, header_size, flags, glyph_count, char_size, height, width = (
        struct.unpack_from("<8I", data, 0)
    )
    if magic != PSF2_MAGIC:
        raise SystemExit("font is not PSF2")
    if version != 0:
        raise SystemExit(f"unsupported PSF2 version {version}")
    if width != 8 or height != 16 or char_size != 16:
        raise SystemExit(
            f"expected 8x16/16-byte glyphs, got {width}x{height}/{char_size}"
        )
    if glyph_count < 256:
        raise SystemExit(f"expected at least 256 glyphs, got {glyph_count}")

    glyph_start = header_size
    glyph_end = glyph_start + 256 * char_size
    if len(data) < glyph_end:
        raise SystemExit("font data is truncated")
    glyphs = data[glyph_start:glyph_end]

    lines: list[str] = [
        "#pragma once",
        "// Generated by scripts/fonts/psf2_to_header.py from kbd default8x16.psfu.",
        "// PSF2 8x16 console font: 256 glyphs, 16 rows per glyph, high bit is leftmost pixel.",
        "",
        "#include <cstdint>",
        "",
        "namespace mochi::font {",
        "",
        "constexpr uint32_t kVga8x16GlyphCount = 256;",
        "constexpr uint32_t kVga8x16Width = 8;",
        "constexpr uint32_t kVga8x16Height = 16;",
        "constexpr uint32_t kVga8x16BytesPerGlyph = 16;",
        "",
        "inline constexpr uint8_t kVga8x16[kVga8x16GlyphCount][kVga8x16BytesPerGlyph] = {",
    ]

    for glyph in range(256):
        rows = glyphs[glyph * char_size : (glyph + 1) * char_size]
        values = ", ".join(f"0x{b:02X}" for b in rows)
        lines.append(f"    /* 0x{glyph:02X} */ {{ {values} }},")

    lines.extend(
        [
            "};",
            "",
            "static inline const uint8_t* vga8x16_glyph(uint32_t codepoint) {",
            "    return kVga8x16[codepoint < kVga8x16GlyphCount ? codepoint : static_cast<uint32_t>('?')];",
            "}",
            "",
            "} // namespace mochi::font",
            "",
        ]
    )
    dst.write_text("\n".join(lines), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
