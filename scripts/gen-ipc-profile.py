#!/usr/bin/env python3
"""Compile config/ipc-profile.conf into the on-image IPC profile.

The output uses the same wire format as mochi/ipc_profile.h (magic, version,
count, 16-byte checksummed entries keyed by FNV-1a of the service name), so the
boot path and any future filesystem copy share one parser.
"""
import argparse
import struct
from pathlib import Path

MAGIC = b"MXIP"
VERSION = 1
MAX_ENTRIES = 32
MAX_BUDGET = 4096


def fnv1a(data: bytes) -> int:
    h = 2166136261
    for byte in data:
        h = ((h ^ byte) * 16777619) & 0xFFFFFFFF
    return h


def parse(text: str):
    entries = []
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        name, sep, value = line.partition("=")
        name, value = name.strip(), value.strip()
        if not sep or not name or len(name) >= 32:
            raise SystemExit(f"ipc-profile:{lineno}: expected name=budget")
        if not value.isdigit() or int(value) > MAX_BUDGET:
            raise SystemExit(f"ipc-profile:{lineno}: budget must be 0..{MAX_BUDGET}")
        entries.append((name, int(value)))
    if len(entries) > MAX_ENTRIES:
        raise SystemExit(f"ipc-profile: at most {MAX_ENTRIES} entries")
    keys = [fnv1a(n.encode()) for n, _ in entries]
    if len(set(keys)) != len(keys):
        raise SystemExit("ipc-profile: duplicate service name")
    return entries


def encode(entries) -> bytes:
    out = bytearray(MAGIC + struct.pack("<HH", VERSION, len(entries)))
    for name, budget in entries:
        name_hash = fnv1a(name.encode())
        payload = struct.pack("<IHH", name_hash, budget, 0) + struct.pack("<I", 0)
        check = fnv1a(payload)
        out += struct.pack("<IHHII", name_hash, budget, 0, check, 0)
    return bytes(out)


def header(blob: bytes) -> str:
    body = ",".join(str(b) for b in blob) if blob else "0"
    return (
        "// Generated by scripts/gen-ipc-profile.py. Do not edit.\n"
        "#pragma once\n"
        f"inline constexpr unsigned kIpcProfileBlobSize = {len(blob)};\n"
        f"inline constexpr unsigned char kIpcProfileBlob[] = {{{body}}};\n"
    )


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", type=Path, required=True)
    ap.add_argument("--header", type=Path, required=True)
    ap.add_argument("--binary", type=Path)
    args = ap.parse_args()
    entries = parse(args.config.read_text()) if args.config.exists() else []
    blob = encode(entries)
    args.header.parent.mkdir(parents=True, exist_ok=True)
    args.header.write_text(header(blob))
    if args.binary:
        args.binary.parent.mkdir(parents=True, exist_ok=True)
        args.binary.write_bytes(blob)


if __name__ == "__main__":
    main()
