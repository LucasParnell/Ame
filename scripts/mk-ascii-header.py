#!/usr/bin/env python3
"""Convert a plain-text ASCII art file into a freestanding C++ header.

The kernel panic screen renders a text logo; keeping the art in a data file
(kernel/assets/*.txt) and generating the header at build time means the image is
never hand-copied into a translation unit. Rows are padded to the widest row so
the renderer can index a rectangular grid.

usage: mk-ascii-header.py INPUT.txt OUTPUT.h NAMESPACE ARRAY_NAME
"""

from __future__ import annotations

import pathlib
import sys


def c_string(text: str) -> str:
    out = ['"']
    for ch in text:
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def main(argv: list[str]) -> int:
    if len(argv) != 5:
        print(f"usage: {argv[0]} INPUT.txt OUTPUT.h NAMESPACE ARRAY_NAME", file=sys.stderr)
        return 2
    src, dst, namespace, name = (pathlib.Path(argv[1]), pathlib.Path(argv[2]),
                                 argv[3], argv[4])
    lines = src.read_text(encoding="utf-8").splitlines()
    # Drop a single trailing empty line from the source; keep interior blanks so
    # the art's shape is preserved.
    while lines and lines[-1] == "":
        lines.pop()
    if not lines:
        raise SystemExit(f"error: {src} has no art rows")
    cols = max(len(line) for line in lines)
    rows = len(lines)
    dst.parent.mkdir(parents=True, exist_ok=True)

    out = [
        "#pragma once",
        f"// Generated by scripts/mk-ascii-header.py from {src.name}. Do not edit.",
        "",
        "#include <cstdint>",
        "",
        f"namespace {namespace} {{",
        "",
        f"constexpr uint32_t {name}Rows = {rows};",
        f"constexpr uint32_t {name}Cols = {cols};",
        "",
        f"inline constexpr const char* {name}[{name}Rows] = {{",
    ]
    for line in lines:
        out.append(f"    {c_string(line.ljust(cols))},")
    out += [
        "};",
        "",
        f"}} // namespace {namespace}",
        "",
    ]
    dst.write_text("\n".join(out), encoding="ascii")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
